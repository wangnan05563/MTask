#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Generate GitHub release notes for MTask from git log.

Usage: python gen-release-notes.py <version> <output_md>
Writes a Markdown release-notes file. Pure stdlib, no third-party deps.
"""
import os
import subprocess
import sys


def _find_repo_root():
    """Walk up from this script to the nearest directory containing .git."""
    d = os.path.dirname(os.path.abspath(__file__))
    for _ in range(10):
        if os.path.isdir(os.path.join(d, ".git")):
            return d
        parent = os.path.dirname(d)
        if parent == d:
            break
        d = parent
    return os.getcwd()


ROOT = _find_repo_root()


def sh(cmd):
    try:
        out = subprocess.run(cmd, shell=True, capture_output=True, text=True, timeout=60,
                             cwd=ROOT, encoding="utf-8", errors="replace")
        return (out.stdout or "").strip()
    except Exception:
        return ""


def main():
    if len(sys.argv) < 3:
        sys.exit("usage: gen-release-notes.py <version> <output_md>")
    version = sys.argv[1]
    out_path = sys.argv[2]

    repo = sh("git remote get-url origin") or "(unknown)"
    branch = sh("git rev-parse --abbrev-ref HEAD") or "master"

    since = sh("git describe --tags --abbrev=0 2>nul")
    if since:
        log = sh('git log ' + since + '..HEAD --pretty=format:"- %s"')
    else:
        log = sh('git log -20 --pretty=format:"- %s"')
    if not log:
        log = "- (no new commits since last tag)"

    notes = (
        "# MTask " + version + "\n\n"
        "Auto-generated by 一键发布.bat\n\n"
        "- Branch: " + branch + "\n"
        "- Repo: " + repo + "\n\n"
        "## Changes\n" + log + "\n"
    )
    with open(out_path, "w", encoding="utf-8") as f:
        f.write(notes)
    print("release notes -> " + out_path)
    return 0


if __name__ == "__main__":
    sys.exit(main())
